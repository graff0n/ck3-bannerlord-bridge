function cultureChains(s, d, prefix, fields) {
  const map = {
    culture: d.cultures.map((k) => ({ cond: `this = culture:${k}`, key: k })),
    heritage: d.heritages.map((k) => ({ cond: `has_cultural_pillar = ${k}`, key: k })),
    unit_gfx: d.unitGfx.map((k) => ({ cond: `has_unit_gfx = ${k}`, key: k })),
    clothing_gfx: d.clothing.map((k) => ({ cond: `has_clothing_gfx = ${k}`, key: k })),
    era: d.eras.map((k) => ({ cond: `has_cultural_era_or_later = ${k}`, key: k })),
    building_gfx: d.buildingGfx.map((k) => ({ cond: `has_building_gfx = ${k}`, key: k })),
  };
  for (const [field, label] of fields) {
    s.comment(label);
    s.chain(
      map[field].map((it) => ({ cond: it.cond, effect: log(`${prefix}|${label}|${it.key}`) })),
      log(`${prefix}|${label}|unknown`),
    );
  }
}

function genEmitEffects(d) {
  const s = newScript('OUT records with static values (docs/PROTOCOL.md 1.2): L, LV, CX, AX, RX.');

  s.comment('this = the battle province, scope:ck3xbl_prov = this. Emits the L lines, then the LV dump (numbers).');
  s.open('ck3xbl_emit_location_effect');
  s.comment('terrain (common/terrain_types)');
  s.chain(d.terrains.map((k) => ({ cond: `terrain = ${k}`, effect: log(`L|terrain|${k}`) })), log('L|terrain|unknown'));
  s.comment('winter severity: the engine swaps these province modifiers as the winter changes');
  s.chain(
    d.winter.map((w) => ({ cond: `has_province_modifier = ${w.modifier}`, effect: log(`L|winter|${w.level}`) })),
    log('L|winter|none'),
  );
  s.comment('holding (common/holdings)');
  s.chain(
    [
      { cond: 'has_holding = no', effect: log('L|holding|none') },
      ...d.holdings.map((k) => ({ cond: `has_holding_type = ${k}`, effect: log(`L|holding|${k}`) })),
    ],
    log('L|holding|other'),
  );
  s.chain([{ cond: 'is_coastal = yes', effect: log('L|coastal|yes') }], log('L|coastal|no'));
  s.chain([{ cond: 'is_riverside_province = yes', effect: log('L|riverside|yes') }], log('L|riverside|no'));
  s.chain([{ cond: 'any_army_in_location = { is_army_in_siege = yes }', effect: log('L|siege|yes') }], log('L|siege|no'));
  s.chain(
    [{ cond: 'OR = { is_raided = yes any_army_in_location = { is_army_in_combat = yes is_raid_army = yes } }', effect: log('L|raid|yes') }],
    log('L|raid|no'),
  );
  s.chain([{ cond: 'is_occupied = yes', effect: log('L|occupied|yes') }], log('L|occupied|no'));
  s.comment('climate region: first match in mapping.json climate_regions order');
  s.chain(d.regions.map((k) => ({ cond: `geographical_region = ${k}`, effect: log(`L|region|${k}`) })), log('L|region|none'));
  s.comment('culture of the place (architecture and local look)');
  s.block('if', (b) => {
    b.line('limit = { exists = culture }');
    b.line('culture = { ck3xbl_emit_l_culture_effect = yes }');
  });
  s.block('else', (b) => {
    b.line(log('L|building_gfx|none'));
    b.line(log('L|loc_culture|none'));
    b.line(log('L|loc_heritage|none'));
  });
  s.comment('numbers cannot be static text: fort level, county development and the attacker origin go into the LV dump');
  s.line('save_scope_value_as = { name = ck3xbl_l_fort value = fort_level }');
  s.block('if', (b) => {
    b.line('limit = { exists = county }');
    b.line('county = { save_scope_value_as = { name = ck3xbl_l_dev value = development_level } }');
  });
  s.line('else = { save_scope_value_as = { name = ck3xbl_l_dev value = 0 } }');
  s.line('ck3xbl_save_attacker_origin_effect = yes');
  s.line(log('LV'));
  s.line('info_log_scopes = yes');
  s.close();
  s.line();

  s.comment('this = culture of the battle province');
  s.block('ck3xbl_emit_l_culture_effect', (b) =>
    cultureChains(b, d, 'L', [['building_gfx', 'building_gfx'], ['culture', 'loc_culture'], ['heritage', 'loc_heritage']]));
  s.line();

  s.comment('this = culture of a character (CX lines follow that character\'s C record)');
  s.block('ck3xbl_emit_cx_culture_effect', (b) =>
    cultureChains(b, d, 'CX', [['culture', 'culture'], ['heritage', 'heritage'], ['unit_gfx', 'unit_gfx'], ['clothing_gfx', 'clothing_gfx'], ['era', 'era']]));
  s.line();

  s.comment('this = culture of an army owner (AX lines follow that army\'s A record)');
  s.block('ck3xbl_emit_ax_culture_effect', (b) =>
    cultureChains(b, d, 'AX', [['culture', 'culture'], ['heritage', 'heritage'], ['unit_gfx', 'unit_gfx'], ['era', 'era']]));
  s.line();

  s.comment('this = culture of a hired regiment\'s owner (RX lines follow that regiment\'s R record)');
  s.block('ck3xbl_emit_rx_culture_effect', (b) =>
    cultureChains(b, d, 'RX', [['culture', 'culture'], ['heritage', 'heritage'], ['unit_gfx', 'unit_gfx']]));
  s.line();

  s.comment('this = character. has_ethnicity has no vanilla use; keys are the CK3 ethnicity database entries.');
  s.block('ck3xbl_emit_cx_ethnicity_effect', (b) =>
    b.chain(d.ethnicities.map((k) => ({ cond: `has_ethnicity = ${k}`, effect: log(`CX|ethnicity|${k}`) })), log('CX|ethnicity|unknown')));
  s.line();

  s.comment('this = character. One line per appearance trait (CX|trait) and per commander trait (CX|ctrait).');
  s.block('ck3xbl_emit_cx_traits_effect', (b) => {
    for (const t of APPEARANCE_TRAITS) b.line(`if = { limit = { has_trait = ${t} } ${log(`CX|trait|${t}`)} }`);
    for (const t of d.commanderTraits) b.line(`if = { limit = { has_trait = ${t} } ${log(`CX|ctrait|${t}`)} }`);
  });
  return s.text();
}

