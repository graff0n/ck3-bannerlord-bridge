function armySlotRegs(i) {
  const b = REG.army.base + REG.army.stride * i;
  const pairs = [...Array(REG.army.maaPairs).keys()].map((k) => ({ type: reg(b + 2 + 2 * k), share: reg(b + 3 + 2 * k) }));
  return { tag: reg(b), levy: reg(b + 1), pairs };
}

function charSlotRegs(j) {
  const b = REG.character.base + REG.character.stride * j;
  return { tag: reg(b), fate: reg(b + 1), killer: reg(b + 2) };
}

function awardSlotRegs(k) {
  const r = awardSlotRegisters(k);
  return { tag: reg(r.tag), award: reg(r.award) };
}

/** Fails the build if the register map overlaps or collides with the checksum register. */
function checkRegisterMap() {
  const used = new Map();
  const claim = (name, owner) => {
    const n = Number(name.slice('ck3xbl_r'.length));
    if (n < 0 || n >= REG.checksum) throw new Error(`${owner}: register ${name} outside the payload range`);
    if (used.has(n)) throw new Error(`${owner}: register ${name} already used by ${used.get(n)}`);
    used.set(n, owner);
  };
  [REG.version, REG.bid, REG.outcome, REG.province, ...Object.values(REG.summary)].forEach((n) => claim(reg(n), 'header'));
  [...Object.values(REG.killTarget), REG.steerHint].forEach((n) => claim(reg(n), 'payload 4 header'));
  for (let i = 0; i < REG.army.slots; i++) {
    const r = armySlotRegs(i);
    [r.tag, r.levy, ...r.pairs.flatMap((p) => [p.type, p.share])].forEach((n) => claim(n, `army slot ${i}`));
  }
  for (let j = 0; j < REG.character.slots; j++) {
    const r = charSlotRegs(j);
    [r.tag, r.fate, r.killer].forEach((n) => claim(n, `character slot ${j}`));
  }
  for (let k = 0; k < AWARD_SLOTS; k++) {
    const r = awardSlotRegs(k);
    [r.tag, r.award].forEach((n) => claim(n, `award slot ${k}`));
  }
}

