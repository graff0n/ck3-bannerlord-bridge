function readJson(name) {
  return JSON.parse(stripBom(readText(path.join(DATA, name))));
}

/** "has_cultural_pillar = heritage_x" -> "heritage_x" */
function rhs(expr) {
  const m = /=\s*([A-Za-z0-9_]+)\s*$/.exec(expr);
  if (!m) throw new Error(`cannot parse chain entry '${expr}'`);
  return m[1];
}

/**
 * Orders gfx keys so that the first key of every culture's list comes before the keys that follow it in any
 * culture's list (CK3 uses the first entry that has an asset; later entries are fallbacks). The first chain
 * match is then the culture's own primary gfx. Ties are broken alphabetically. A cycle (1.20 has one:
 * ancient_egyptian lists mena before byzantine, assyrian the reverse) is broken at the alphabetically smallest
 * remaining key and reported as a note; loadInputs warns if any culture would then print a non-primary gfx.
 */
function precedenceOrder(lists, notes, label) {
  const keys = new Set(lists.flat());
  const after = new Map([...keys].map((k) => [k, new Set()]));
  const indegree = new Map([...keys].map((k) => [k, 0]));
  for (const list of lists) {
    for (let i = 0; i < list.length; i++) {
      for (let j = i + 1; j < list.length; j++) {
        const a = list[i];
        const b = list[j];
        if (a !== b && !after.get(a).has(b)) {
          after.get(a).add(b);
          indegree.set(b, indegree.get(b) + 1);
        }
      }
    }
  }
  const order = [];
  const remaining = new Set(keys);
  while (remaining.size) {
    const ready = [...remaining].filter((k) => indegree.get(k) === 0).sort();
    let next = ready[0];
    if (!next) {
      next = [...remaining].sort()[0];
      notes.push(`${label}: precedence cycle resolved by placing ${next} first`);
    }
    remaining.delete(next);
    order.push(next);
    for (const b of after.get(next)) indegree.set(b, indegree.get(b) - 1);
  }
  return order;
}

export function loadInputs() {
  const catalog = readJson('ck3_catalog.json');
  const mapping = readJson('mapping.json');
  const maaIndex = readJson('ck3_maa_index.json');
  const terrainScenes = readJson('terrain_scenes.json');
  const game = gameDir();
  if (!fs.existsSync(game)) throw new Error(`CK3 game folder not found: ${game} (set CK3_GAME_DIR)`);

  const warnings = [];
  const notes = [];
  const emit = mapping.ck3_emit;
  const cultures = Object.keys(catalog.cultures).sort();
  const clothingLists = cultures.map((c) => catalog.cultures[c].clothing_gfx || []).filter((l) => l.length);
  const clothing = precedenceOrder(clothingLists, notes, 'clothing_gfx');
  for (const c of cultures) {
    const own = catalog.cultures[c].clothing_gfx || [];
    if (own.length && clothing.find((k) => own.includes(k)) !== own[0]) {
      warnings.push(`clothing_gfx: culture ${c} would print ${clothing.find((k) => own.includes(k))} instead of ${own[0]}`);
    }
  }

  // castle_holding first (by far the most common holding at a battle site), then alphabetical.
  const holdings = [...topLevelBlockKeys(path.join(game, 'common', 'holdings'))]
    .sort((a, b) => (a === 'castle_holding' ? -1 : b === 'castle_holding' ? 1 : a.localeCompare(b)));
  const ethnicities = [...topLevelBlockKeys(path.join(game, 'common', 'ethnicities'))]
    .filter((k) => !ETHNICITY_TEMPLATES.has(k))
    .sort();

  const winter = emit.winter_chain.map(rhs).map((modifier) => {
    const m = /^winter_([a-z]+)_modifier$/.exec(modifier);
    if (!m) throw new Error(`unexpected winter modifier ${modifier}`);
    return { modifier, level: m[1] };
  });

  return {
    warnings,
    notes,
    cultures,
    heritages: emit.heritage_chain.map(rhs),
    unitGfx: mapping.unit_gfx_test_order,
    clothing,
    eras: emit.era_chain.map(rhs),
    terrains: emit.terrain_chain.map(rhs),
    regions: mapping.climate_regions.map((r) => r.region),
    winter,
    commanderTraits: emit.commander_traits,
    buildingGfx: terrainScenes.siege.architecture.ck3_chain_order,
    maa: maaIndex.keys,
    holdings,
    ethnicities,
    knights: knightInputs(),
    maluses: malusSources(game),
  };
}

// Vanilla sources of a negative army_damage_mult / army_toughness_mult on an army owner (lever headroom): a realm
// law is a block whose modifier block holds the tag, a character modifier or a trait is a top-level definition holding it anywhere.
const MALUS_DIRS = ['common/laws', 'common/modifiers', 'common/traits'];
const MALUS_TAGS = ['army_damage_mult', 'army_toughness_mult'];

function malusSources(game) {
  const out = Object.fromEntries(MALUS_TAGS.map((t) => [t, []]));
  const add = (tag, trigger, key, node, file) => out[tag].push({
    trigger, key, amount: Number(node.value), where: `${path.relative(game, file).replace(/\\/g, '/')}:${node.line}`,
  });
  const isMalus = (n) => MALUS_TAGS.includes(n.key) && Number(n.value) < 0;
  for (const file of listFiles(path.join(game, 'common', 'laws'), ['.txt'])) {
    walk(parseText(readText(file)), (n, parents) => {
      const law = parents[parents.length - 2];
      if (isMalus(n) && parents[parents.length - 1]?.key === 'modifier' && law) add(n.key, 'has_realm_law', law.key, n, file);
    });
  }
  for (const [dir, trigger] of [['modifiers', 'has_character_modifier'], ['traits', 'has_trait']]) {
    for (const file of listFiles(path.join(game, 'common', dir), ['.txt'])) {
      for (const def of parseText(readText(file))) {
        if (def.key && def.block) walk(def.block, (n) => isMalus(n) && add(n.key, trigger, def.key, n, file));
      }
    }
  }
  for (const tag of MALUS_TAGS) if (!out[tag].length) throw new Error(`no vanilla malus on ${tag} found in ${MALUS_DIRS.join(', ')}`);
  return out;
}

const TXP_RECORD = /^CX\|txp\|[A-Za-z0-9_]+(?::[A-Za-z0-9_]+)?\|<level>$/;

/** Inputs of the knights records (docs/PROTOCOL.md 13.2): combat traits, knight effectiveness, accolades, artifacts. */
function knightInputs() {
  const combat = readJson('ck3_combat_traits.json');
  const plan = combat.emitPlan;
  const emitOf = (k) => {
    const emit = combat.traits[k]?.emit;
    if (!emit) throw new Error(`ck3_combat_traits.json: trait ${k} of the emit plan has no emit block`);
    return emit;
  };
  const combatTraits = plan.traitsNotEmittedToday.map((k) => {
    const emit = emitOf(k);
    if (emit.record !== `CX|ktrait|${k}`) throw new Error(`ck3_combat_traits.json: ${k} emits '${emit.record}', expected CX|ktrait|${k}`);
    return { key: k, trigger: emit.trigger };
  });
  const leveledTraits = plan.traitsWithLevels.map((k) => {
    const emit = emitOf(k);
    for (const track of emit.levels) {
      if (!TXP_RECORD.test(track.record)) throw new Error(`ck3_combat_traits.json: ${k} track ${track.track}: unexpected record '${track.record}'`);
    }
    return { key: k, trigger: emit.trigger, tracks: emit.levels.map((t) => ({ record: t.record, chain: t.chain })) };
  });
  const ownerTraits = Object.keys(combat.traits).filter((k) => (combat.traits[k].roles || []).includes('armyOwner')).sort();
  const keSources = readJson('ck3_knight_effectiveness_sources.json');
  return {
    combatTraits,
    leveledTraits,
    ownerTraits,
    cultureParams: plan.cultureParameters,
    faithParams: plan.faithParameters,
    keSources: keSources.sources,
    keHash: keSources.meta.content_hash,
    accoladeTypes: Object.keys(readJson('ck3_accolade_types.json').types),
    artifactTypes: readJson('ck3_artifact_types.json'),
  };
}

