// ---------------------------------------------------------------------------------------------------------------
// Saved scopes the pulse chain drops (PROTOCOL 14.5; live test 2026-10-04: every ST|P dump repeated about 100 saved scopes of
// the snapshot, because the first pulse inherits the apply's event chain and every pulse hands its scopes to the next)
// ---------------------------------------------------------------------------------------------------------------

// Engine-saved scopes an event chain of the mod may inherit (on_action scopes; lint_ck3_mod.mjs ON_ACTION_SAVED_SCOPES).
const ENGINE_SAVED_SCOPES = ['army', 'wipe'];
// What the pulse (ck3xbl_clock.0001) needs from the event that triggered it: the chain id its trigger compares.
const PULSE_KEEPS = ['ck3xbl_chain'];

/** Every name saved in `texts` (save_scope_as, save_scope_value_as and their temporary forms; comments ignored), sorted. */
export function savedScopeNames(texts) {
  const names = new Set();
  for (const text of texts) {
    const code = stripBom(text).split(/\r?\n/).map((l) => l.replace(/#.*$/, '')).join('\n');
    for (const m of code.matchAll(/\bsave_(?:temporary_)?scope_as\s*=\s*(\w+)|\bsave_(?:temporary_)?scope_value_as\s*=\s*\{\s*name\s*=\s*(\w+)/g)) {
      names.add(m[1] || m[2]);
    }
  }
  return [...names].sort();
}

/** The pulse's scope reset: every name the mod saves (hand-written files on disk, generated ones as rendered now) but the keeps. */
function genScopeEffects(d) {
  const texts = [...(d.generatedTexts?.values() || [])];
  for (const file of listFiles(MOD, ['.txt'], true)) {
    const text = readText(file);
    if (!isGenerated(text)) texts.push(text);
  }
  const names = [...new Set([...savedScopeNames(texts), ...ENGINE_SAVED_SCOPES])].filter((n) => !PULSE_KEEPS.includes(n)).sort();
  const s = newScript('Saved scopes the pulse of the battle clock drops (docs/PROTOCOL.md 14.5).', 'every save_scope_as / save_scope_value_as of the mod');
  s.comment('this = the player in ck3xbl_clock.0001, before anything else. A pulse inherits the saved scopes of whatever triggered it: the');
  s.comment('first one the event chain of the snapshot and the apply, every later one the previous pulse. All of them are dropped except');
  s.comment(`${PULSE_KEEPS.join(', ')}, so every ST record of the pulse carries only what the pulse itself saved (the bridge reads only its`);
  s.comment('listed keys anyway). Combat, side and army scopes would die with their objects; values just grew the dumps.');
  s.block('ck3xbl_st_clear_carried_scopes_effect', (b) => {
    for (const n of names) b.line(`if = { limit = { exists = scope:${n} } clear_saved_scope = ${n} }`);
  });
  return s.text();
}

