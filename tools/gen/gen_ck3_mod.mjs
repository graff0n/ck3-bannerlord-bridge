#!/usr/bin/env node
// gen_ck3_mod.mjs - generates the static, data-driven parts of the CK3 mod "ck3xbl".
//
// CK3 script cannot print a key or address a variable by a computed name, so everything that depends on data
// tables (culture/heritage/gfx/terrain/region keys, the 111 men-at-arms types, the 200 keypad registers and the
// per-slot apply code) is expanded here into plain if/else_if chains. The output is static text: it never changes
// at runtime, which keeps the game checksum stable (achievements) and the mod free of runtime-written files.
//
// Inputs (read-only):
//   bridge/data/ck3_catalog.json     culture keys and their clothing_gfx lists
//   bridge/data/mapping.json         ck3_emit chains (heritage, era, terrain, winter, commander traits), unit_gfx_test_order, climate_regions
//   bridge/data/ck3_maa_index.json   1-based men-at-arms index used by the keypad payload (docs/PROTOCOL.md 2.2)
//   bridge/data/terrain_scenes.json  siege.architecture.ck3_chain_order (building gfx test order)
//   bridge/data/ck3_combat_traits.json         emitPlan + traits.<k>.emit (CX|ktrait/txp/cparam/fparam, AX|otrait/ocparam/ofparam)
//   bridge/data/ck3_knight_effectiveness_sources.json  every knight effectiveness source (ck3xbl_a_ke)
//   bridge/data/ck3_accolade_types.json        accolade type keys (CX|acc_*)
//   bridge/data/ck3_artifact_types.json        battle artifact types and helmet features (CX|artifact*)
//   the CK3 install (CK3_GAME_DIR)   holding types and ethnicities (keys only); the vanilla maluses on army_damage_mult /
//                                    army_toughness_mult in common/laws, common/modifiers, common/traits (battle clock headroom)
//   tools/gen/lib/steering.mjs       battle clock constants (steering modifiers, day markers, phase-event shield)
//   tools/gen/knights/               the renderers shared with the knights tools (knight_eff_emit.mjs, accolade_emit.mjs,
//                                    emit_artifacts.mjs), so the mod prints exactly their script
// Outputs: the files listed in OUTPUTS under ck3_mod/ck3xbl, each starting with GENERATED_MARK (a localization file
// right after its l_<language>: line). Files are rewritten
// only when their content changes, and generated files that are no longer produced are deleted.
//
// Usage: node tools/gen/gen_ck3_mod.mjs [--check]
//   --check  write nothing; exit 1 if any output differs from what is on disk (idempotency / drift check).

