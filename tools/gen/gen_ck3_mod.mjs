function main() {
  const check = process.argv.includes('--check');
  checkRegisterMap();
  const data = loadInputs();
  data.generatedTexts = new Map();
  const produced = new Set();
  const changed = [];
  for (const [rel, gen] of OUTPUTS) {
    const file = path.join(MOD, ...rel.split('/'));
    produced.add(path.resolve(file));
    const text = gen(data);
    data.generatedTexts.set(rel, text);
    if (writeWithBom(file, text, { dryRun: check })) changed.push(rel);
  }
  // Delete generated files that this version no longer produces.
  for (const file of listFiles(MOD, ['.txt', '.gui', '.yml'], true)) {
    if (produced.has(path.resolve(file))) continue;
    if (isGenerated(readText(file))) {
      changed.push(`${path.relative(MOD, file).replace(/\\/g, '/')} (stale, removed)`);
      if (!check) fs.unlinkSync(file);
    }
  }
  for (const n of data.notes) console.log(`note: ${n}`);
  for (const w of data.warnings) console.log(`warning: ${w}`);
  console.log(`inputs: ${data.cultures.length} cultures, ${data.heritages.length} heritages, ${data.unitGfx.length} unit_gfx, ` +
    `${data.clothing.length} clothing_gfx, ${data.eras.length} eras, ${data.terrains.length} terrains, ${data.regions.length} regions, ` +
    `${data.buildingGfx.length} building_gfx, ${data.holdings.length} holdings, ${data.ethnicities.length} ethnicities, ${data.maa.length} MaA types`);
  if (changed.length === 0) {
    console.log('up to date: no generated file changed');
    return;
  }
  for (const c of changed) console.log(`${check ? 'would change' : 'wrote'}: ${c}`);
  if (check) process.exitCode = 1;
}

