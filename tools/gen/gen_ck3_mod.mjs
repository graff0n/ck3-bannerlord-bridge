// ---------------------------------------------------------------------------------------------------------------
// Script text builder
// ---------------------------------------------------------------------------------------------------------------

class Script {
  constructor() {
    this.lines = [];
    this.depth = 0;
  }
  line(text = '') {
    this.lines.push(text === '' ? '' : '\t'.repeat(this.depth) + text);
    return this;
  }
  comment(text) {
    return this.line(`# ${text}`);
  }
  open(head, op = '=') {
    this.line(`${head} ${op} {`);
    this.depth++;
    return this;
  }
  close() {
    this.depth--;
    return this.line('}');
  }
  block(head, body, op = '=') {
    this.open(head, op);
    body(this);
    return this.close();
  }
  /** One-line if/else_if chain: items = [{cond, effect}], fallback = effect text or null. */
  chain(items, fallback) {
    items.forEach((item, i) => this.line(`${i === 0 ? 'if' : 'else_if'} = { limit = { ${item.cond} } ${item.effect} }`));
    if (fallback) this.line(`else = { ${fallback} }`);
    return this;
  }
  text() {
    return this.lines.join('\n') + '\n';
  }
}

const DATA_INPUTS = 'bridge/data/*.json and the CK3 install';

function fileHeader(purpose, inputs) {
  return [GENERATED_MARK, `# ${purpose}`, `# Inputs: ${inputs}. Regenerate: node tools/gen/gen_ck3_mod.mjs`, ''];
}

function newScript(purpose, inputs = DATA_INPUTS) {
  const s = new Script();
  for (const l of fileHeader(purpose, inputs)) s.line(l);
  return s;
}

/**
 * True for a file this generator wrote: the mark is the first line, or, in a localization file (whose first line must be
 * `l_<language>:`), the first entry after it.
 */
function isGenerated(text) {
  const lines = stripBom(text).split(/\r?\n/);
  return lines[0] === GENERATED_MARK || (/^l_[a-z_]+:$/.test(lines[0]) && (lines[1] || '').trim() === GENERATED_MARK);
}

