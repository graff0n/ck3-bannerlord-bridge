/** "+25%" / "-10%" for a step in percent points. */
const percent = (pp) => `${pp > 0 ? '+' : ''}${pp}%`;
/** A decimal for script: 0.25, -0.1, 19 (no float noise). */
const decimal = (x) => String(Math.round(x * 100000) / 100000);

/**
 * The lever modifiers of the configured form. 'scale': ck3xbl_st_<lever>_<up|down>, each scaled by the receiver's variable of
 * the same name. 'ladder': ck3xbl_st_<lever>_s<k>, one per fixed step inside the lever's caps (fallback).
 */
function leverModifiers(st) {
  if (st.MODIFIER_FORM === 'ladder') {
    return st.LEVERS.flatMap((l) => ladderSteps(st, l).map((pp, k) => ({
      name: `ck3xbl_st_${l.key}_s${k + 1}`,
      lever: l.key,
      tag: l.modifier,
      amount: decimal(pp / 100),
      pp,
      icon: pp > 0 ? 'martial_positive' : 'martial_negative',
      title: `${pp > 0 ? l.up : l.down} (${percent(pp)})`,
    })));
  }
  return st.LEVERS.flatMap((l) => ['up', 'down'].map((dir) => ({
    name: `ck3xbl_st_${l.key}_${dir}`,
    lever: l.key,
    dir,
    tag: l.modifier,
    amount: decimal(dir === 'up' ? st.LEVER_STEP : -st.LEVER_STEP),
    icon: dir === 'up' ? 'martial_positive' : 'martial_negative',
    title: l[dir],
    scale: scaleValueOf(`ck3xbl_st_${l.key}_${dir}`),
  })));
}

/** The ladder steps of a lever that its caps allow (percent points, ascending, no 0). */
function ladderSteps(st, lever) {
  const steps = st.LADDER_STEPS[lever.key];
  if (!steps) throw new Error(`steering.mjs: no LADDER_STEPS for lever ${lever.key}`);
  return steps.filter((pp) => pp >= -lever.downMax && pp <= lever.upMax);
}

/** Percent points the down lever of `lever` may take at most on this owner: a headroom value, or the constant cap. */
function downLimit(st, lever) {
  return lever.key === 'knight' ? String(Math.min(st.KNIGHT_DOWN_MAX, st.MALUS_FLOOR)) : `ck3xbl_st_${lever.key}_headroom_value`;
}

